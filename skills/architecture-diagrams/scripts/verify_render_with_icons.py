#!/usr/bin/env python3
"""
Internal verification renderer -- NOT a replacement for opening the file in draw.io,
and not something to show the user by default (see SKILL.md "On previews"). This exists
for Claude's own use: a quick sanity check that a generated/edited .drawio file's icons,
colors, and layout look like what was intended, before delivering the file.

Unlike scripts/render_drawio_svg.py (the older, icon-blind renderer kept for the
non-default "rough check" case), this one decodes and draws the actual embedded
image=data:image/svg+xml;base64,... icons from each cell's style -- including icons
generated by generate_icons.py and any others a diagram happens to embed -- so it's
useful for verifying "create from scratch" diagrams that lean on icon_data_uris.json.
It auto-derives icon placement directly from each cell's own style string, so it does
NOT need a hardcoded cell-id -> icon-name map specific to any one diagram.

Usage:
    python3 verify_render_with_icons.py path/to/diagram.drawio path/to/output.png [page_w] [page_h]

Requires: Pillow (required), cairosvg (optional — icon rendering only). If cairosvg
isn't installed, this script still runs and produces a PNG with icon boxes left blank
(a placeholder outline instead of the decoded icon image) rather than crashing outright
— it prints a warning once so the gap is visible, and the caller should fall back to
scripts/render_drawio_svg.py's XML-only check for icon-level verification instead of
trusting this output as a full visual check.
"""
import sys
import os
import re
import math
import base64
import tempfile
from html import unescape
from xml.etree import ElementTree as ET

from PIL import Image, ImageDraw, ImageFont

try:
    import cairosvg
except ImportError:
    cairosvg = None
    print("WARNING: cairosvg not installed — icons will render as blank placeholder boxes, "
          "not the actual decoded SVG images. This is not a full visual check; treat it the "
          "same as scripts/render_drawio_svg.py's XML-only fallback and say so explicitly.",
          file=sys.stderr)


def parse_style(s):
    """Parse a draw.io style string into a dict.

    Special case: an `image=data:...;base64,...` value contains a literal `;` as part
    of the data URI itself (between the mime type and `base64,`), which collides with
    draw.io's own `;`-separated style syntax. A naive `s.split(';')` truncates the image
    value at that inner semicolon and silently drops the rest of the payload. Detect an
    `image=data:` fragment and re-join it with the very next fragment before treating
    the rest of the string normally.
    """
    props = {}
    if not s:
        return props
    parts = s.split(";")
    merged = []
    i = 0
    while i < len(parts):
        p = parts[i]
        if p.startswith("image=data:") and i + 1 < len(parts):
            merged.append(p + ";" + parts[i + 1])
            i += 2
        else:
            merged.append(p)
            i += 1
    for p in merged:
        if "=" in p:
            k, v = p.split("=", 1)
            props[k] = v
    return props


def clean_label(value):
    if not value:
        return []
    text = unescape(value)
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.I)
    text = re.sub(r"<[^>]+>", "", text)
    return [l.strip() for l in text.split("\n") if l.strip()]


def hex2rgb(h, default=(255, 255, 255)):
    if not h or h == "none":
        return None
    h = h.lstrip("#")
    if len(h) != 6:
        return default
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def decode_icon_to_png(data_uri, size, tmp_dir, cache):
    if data_uri in cache:
        return cache[data_uri]
    try:
        b64 = data_uri.split(",", 1)[1]
        svg_bytes = base64.b64decode(b64)
        tmp_path = os.path.join(tmp_dir, f"icon_{len(cache)}.png")
        cairosvg.svg2png(bytestring=svg_bytes, write_to=tmp_path,
                          output_width=size, output_height=size)
        im = Image.open(tmp_path).convert("RGBA")
        cache[data_uri] = im
        return im
    except Exception as e:
        print(f"  (icon decode failed, skipping: {e})", file=sys.stderr)
        return None


def render(drawio_path, out_png, page_w=1700, page_h=900):
    tree = ET.parse(drawio_path)
    model = tree.getroot().find(".//mxGraphModel")
    if model is None:
        raise ValueError("No <mxGraphModel> found -- is this a valid .drawio file?")
    r = model.find("root")
    cellmap = {}
    for c in r.findall("mxCell"):
        g = c.find("mxGeometry")
        cellmap[c.get("id")] = {
            "value": c.get("value", ""), "style": parse_style(c.get("style", "")),
            "parent": c.get("parent"), "vertex": c.get("vertex") == "1",
            "edge": c.get("edge") == "1", "source": c.get("source"), "target": c.get("target"),
            "geom": g.attrib if g is not None else {},
        }

    cache = {}

    def abs_box(cid):
        if cid in cache:
            return cache[cid]
        c = cellmap[cid]
        g = c["geom"]
        x, y = float(g.get("x", 0)), float(g.get("y", 0))
        w, h = float(g.get("width", 0)), float(g.get("height", 0))
        p = c["parent"]
        if p in cellmap and cellmap[p]["vertex"]:
            px, py, pw, ph = abs_box(p)
            x += px
            y += py
        cache[cid] = (x, y, w, h)
        return cache[cid]

    img = Image.new("RGB", (page_w, page_h), (255, 255, 255))
    draw = ImageDraw.Draw(img, "RGBA")

    def find_font(paths, size):
        for p in paths:
            if os.path.exists(p):
                return ImageFont.truetype(p, size)
        return ImageFont.load_default()

    font_reg = find_font(["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"], 12)
    font_bold = find_font(["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"], 12)
    font_small = find_font(["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"], 10)
    font_italic = find_font(["/usr/share/fonts/truetype/dejavu/DejaVuSans-Oblique.ttf"], 10)

    verts = [c for c in r.findall("mxCell") if c.get("vertex") == "1"]

    def area(c):
        x, y, w, h = abs_box(c.get("id"))
        return w * h

    verts.sort(key=area, reverse=True)

    icon_cache = {}
    with tempfile.TemporaryDirectory() as tmp_dir:
        for c in verts:
            cid = c.get("id")
            x, y, w, h = abs_box(cid)
            if w == 0 or h == 0:
                continue
            st = cellmap[cid]["style"]
            fill = hex2rgb(st.get("fillColor"))
            stroke_color = st.get("strokeColor")
            stroke = hex2rgb(stroke_color, default=(71, 94, 117)) if stroke_color not in (None, "none") else None
            sw = max(1, int(float(st.get("strokeWidth", 1.5))))
            rx = 14 if st.get("rounded") == "1" else 0
            box = [x, y, x + w, y + h]
            if st.get("shadow") == "1" and fill:
                draw.rounded_rectangle([x + 4, y + 5, x + w + 4, y + h + 5], radius=rx, fill=(0, 0, 0, 28))
            if fill:
                draw.rounded_rectangle(box, radius=rx, fill=fill, outline=stroke, width=sw)
            elif stroke:
                draw.rounded_rectangle(box, radius=rx, outline=stroke, width=sw)

            img_uri = st.get("image")
            has_img = bool(img_uri and img_uri.startswith("data:image"))
            if has_img:
                icon_size = int(float(st.get("imageWidth", 30)))
                icon_im = decode_icon_to_png(img_uri, icon_size, tmp_dir, icon_cache)
                if icon_im:
                    img.paste(icon_im, (int(x + 8), int(y + h / 2 - icon_size / 2)), icon_im)

            lines = clean_label(cellmap[cid]["value"])
            fontsize = float(st.get("fontSize", 12))
            f = font_bold if st.get("fontStyle") == "1" else (font_italic if st.get("fontStyle") == "2" else font_reg)
            if fontsize <= 10:
                f = font_small if st.get("fontStyle") != "1" else font_bold
            color = hex2rgb(st.get("fontColor"), default=(26, 39, 51))
            align = st.get("align", "center")
            text_x = x + (46 if has_img else w / 2)
            if align == "right":
                text_x = x + w - 8
            elif align == "left" and not has_img:
                text_x = x + float(st.get("spacingLeft", 8) or 8)
            line_h = fontsize * 1.3
            start_y = y + h / 2 - (line_h * len(lines)) / 2
            for i, l in enumerate(lines):
                ly = start_y + i * line_h
                bbox = draw.textbbox((0, 0), l, font=f)
                lw = bbox[2] - bbox[0]
                if align == "center" and not has_img:
                    draw.text((text_x - lw / 2, ly), l, fill=color, font=f)
                elif align == "right":
                    draw.text((text_x - lw, ly), l, fill=color, font=f)
                else:
                    draw.text((text_x, ly), l, fill=color, font=f)

        edges = [c for c in r.findall("mxCell") if c.get("edge") == "1"]
        for c in edges:
            st = cellmap[c.get("id")]["style"]
            stroke = hex2rgb(st.get("strokeColor"), default=(71, 94, 117))
            sw = max(1, int(float(st.get("strokeWidth", 1.5))))
            dashed = st.get("dashed") == "1"
            src, tgt = c.get("source"), c.get("target")
            if src in cellmap and tgt in cellmap:
                sx, sy, sw_, sh = abs_box(src)
                tx, ty, tw, th = abs_box(tgt)
                if tx >= sx:
                    x1, y1 = sx + sw_, sy + sh / 2
                    x2, y2 = tx, ty + th / 2
                else:
                    x1, y1 = sx, sy + sh / 2
                    x2, y2 = tx + tw, ty + th / 2
                if dashed:
                    dist = math.hypot(x2 - x1, y2 - y1)
                    n = max(1, int(dist / 8))
                    for i in range(n):
                        if i % 2 == 0:
                            xa = x1 + (x2 - x1) * i / n
                            ya = y1 + (y2 - y1) * i / n
                            xb = x1 + (x2 - x1) * (i + 1) / n
                            yb = y1 + (y2 - y1) * (i + 1) / n
                            draw.line([xa, ya, xb, yb], fill=stroke, width=sw)
                else:
                    draw.line([x1, y1, x2, y2], fill=stroke, width=sw)
                    ang = math.atan2(y2 - y1, x2 - x1)
                    ah = 8
                    p1 = (x2 - ah * math.cos(ang - 0.4), y2 - ah * math.sin(ang - 0.4))
                    p2 = (x2 - ah * math.cos(ang + 0.4), y2 - ah * math.sin(ang + 0.4))
                    draw.polygon([(x2, y2), p1, p2], fill=stroke)
                lbl = clean_label(cellmap[c.get("id")]["value"])
                if lbl:
                    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
                    max_w = max(draw.textbbox((0, 0), l, font=font_small)[2] for l in lbl)
                    box_h = 12 * len(lbl) + 4
                    draw.rectangle([mx - max_w / 2 - 4, my - box_h / 2, mx + max_w / 2 + 4, my + box_h / 2],
                                    fill=(255, 255, 255, 235))
                    for i, l in enumerate(lbl):
                        bbox = draw.textbbox((0, 0), l, font=font_small)
                        lw = bbox[2] - bbox[0]
                        draw.text((mx - lw / 2, my - box_h / 2 + 2 + i * 12), l, fill=stroke, font=font_small)

    img.save(out_png)
    print(f"saved {out_png}")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    drawio_path, out_png = sys.argv[1], sys.argv[2]
    page_w = int(sys.argv[3]) if len(sys.argv) > 3 else 1700
    page_h = int(sys.argv[4]) if len(sys.argv) > 4 else 900
    render(drawio_path, out_png, page_w, page_h)
