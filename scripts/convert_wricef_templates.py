# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    repo_root = Path(__file__).parent.parent
    specs_dir = repo_root / "workspace" / "specs"
    artifacts_dir = repo_root / "artifacts"

    for spec in SPECS:
        # support files in workspace/specs/ subdirs (e.g. other/)
        src = specs_dir / spec["file"]
        if not src.exists():
            # try workspace/ root for files in subdirs like "other/"
            src = repo_root / "workspace" / spec["file"]
        if not src.exists():
            print(f"SKIP (not found): {spec['file']}", file=sys.stderr)
            continue

        out_dir = artifacts_dir / spec["slug"]
        out_dir.mkdir(parents=True, exist_ok=True)

        print(f"Converting {spec['file']} ...")
        doc = _open_word(src)

        # markdown template
        if spec.get("scenario"):
            md = doc_to_markdown_scenario(doc, spec["label"])
        else:
            md = doc_to_markdown(doc, spec["label"])
        (out_dir / "template.md").write_text(md, encoding="utf-8")

        # schema — extract H2 section names as properties
        sections = [
            p.text.strip()
            for p in doc.paragraphs
            if p.style.name in ("Heading 2", "Heading 3", "Appendix")
            and p.text.strip()
        ]
        schema = make_schema(spec["label"], sections)
        (out_dir / "schema.json").write_text(
            json.dumps(schema, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )

        # empty meta (factory pattern)
        meta = out_dir / "artifact.meta.md"
        if not meta.exists():
            meta.write_text("", encoding="utf-8")

        print(f"  → artifacts/{spec['slug']}/")

    print("Done.")


if __name__ == "__main__":
    main()
