#!/usr/bin/env python3
"""Install this factory's own-posture skills, agents, assistants, and connectors into a client
project for Claude Code.

Usage:
    python3 scripts/claude-code/adapter/install.py \\
        --project /path/to/client-project \\
        --skills fit-to-standard,defect-triage \\
        --agents defect-classifier \\
        --assistants solution-architect \\
        --connectors jira \\
        [--destination jira=myclient] \\
        [--check] [--force]

`--skills`/`--agents`/`--assistants`/`--connectors` accept a comma-separated list or the literal
'*' (all own-posture skills / agents / assistants / all connectors with real, non-placeholder
wiring). Writes into <project>/.claude/skills/, <project>/.claude/agents/, <project>/tools/,
<project>/.mcp.json, <project>/CLAUDE.md, and <project>/factory-lock.json. Never touches this
repo's own skills/, agents/, assistants/, or connectors/ trees -- see
scripts/claude-code/adapter/README.md for why that matters (a real data-loss bug was found in
the manual `skills add` process this replaces).

Agents and Assistants are each written as a single synthesized `.md` file (Claude Code's own
subagent convention, unlike skills' per-skill folder), since agent.md/assistant.md themselves
carry no frontmatter -- see adapter_common.py's agent_output_bytes()/assistant_output_bytes()
for exactly what gets added and why. Claude Code has no separate "Assistant" primitive, so an
Assistant installs into the same .claude/agents/ directory an Agent does.

Any Tool a requested Skill's skill.meta.md Dependency graph declares (type `tool`) is copied
into <project>/tools/<name>/ automatically -- a Skill's own instructions reference its Tool's
script at that relative path (e.g. tools/calculate-s4hana-sizing/scripts/sizing_calc.py), so it
must exist there for the Skill to actually work once unpacked, not just be documented.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import adapter_common as common  # noqa: E402

TOOL = "claude-code"
ADOPT_HINT = "npx skills add /path/to/sap-ai-factory -a claude-code -s '*' --copy -y"


def write_mcp_json(project, all_entries):
    path = project / ".mcp.json"
    existing = common.load_json(path, {})
    servers = existing.setdefault("mcpServers", {})
    servers.update(all_entries)
    common.write_json(path, existing)


def write_claude_md(project, installed_skills, installed_agents, installed_assistants, installed_connectors, seeded_knowledge, seeded_artifacts, version):
    lines = [
        "<!-- Generated by sap-ai-factory's Claude Code adapter",
        "     (scripts/claude-code/adapter/install.py). Do not hand-edit -- rerun the adapter",
        "     instead; it will overwrite this file. -->",
        "",
        "# SAP AI Factory -- installed components",
        "",
        f"Factory version: `{version}`  ",
        f"Generated: {common.now_iso()}",
        "",
        "## Skills",
        "",
    ]
    for name in installed_skills:
        desc = common.component_desc("Skill", name)
        lines.append(f"- **{name}** -- {desc}" if desc else f"- **{name}**")
    if installed_assistants:
        lines += ["", "## Assistants", ""]
        for name in installed_assistants:
            desc = common.component_desc("Assistant", name)
            lines.append(f"- **{name}** -- {desc}" if desc else f"- **{name}**")
    if installed_agents:
        lines += ["", "## Agents", ""]
        for name in installed_agents:
            desc = common.component_desc("Agent", name)
            lines.append(f"- **{name}** -- {desc}" if desc else f"- **{name}**")
    if installed_connectors:
        lines += ["", "## Connectors", ""]
        for name in installed_connectors:
            desc = common.component_desc("Connector", name)
            line = f"- **{name}** -- {desc}" if desc else f"- **{name}**"
            line += (
                f" Credentials are not wired by this adapter -- follow the \"Wiring\" section in "
                f"connectors/{name}/connector.md."
            )
            lines.append(line)
    if seeded_knowledge or seeded_artifacts:
        lines += ["", "## Knowledge & artifacts", "",
                   "Seeded once from the factory's central defaults; this adapter never overwrites "
                   "them again on a later run -- they're yours to edit per file from here on."]
        if seeded_knowledge:
            lines.append("- Knowledge buckets: " + ", ".join(f"`knowledge/{b}/`" for b in seeded_knowledge))
        if seeded_artifacts:
            lines.append("- Artifact templates: " + ", ".join(f"`artifacts/{a}/`" for a in seeded_artifacts))
    lines.append("")
    (project / "CLAUDE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def prune_orphaned_lock_entries(lock):
    """Drops lock entries whose factory `source` no longer exists on disk. Previously install.py
    never pruned these, so a component removed from the factory (or renamed without updating the
    lock) lingered in every already-installed client's factory-lock.json forever -- the
    ORPHANED-LOCK case scripts/sync_back.py's --check must tolerate rather than crash on when
    hash_tree hits the missing path. Pruning here at the source keeps that a rare edge case
    instead of the steady state. Returns {section: [pruned names]} for a printed note."""
    pruned = {}
    for section in ("skills", "agents", "assistants", "tools", "connectors", "knowledge", "artifacts"):
        gone = [
            name for name, entry in lock[section].items()
            if entry.get("source") and not (common.FACTORY_ROOT / entry["source"]).exists()
        ]
        for name in gone:
            del lock[section][name]
        if gone:
            pruned[section] = gone
    return pruned


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", required=True, help="path to the client project to install into")
    parser.add_argument("--skills", default="", help="comma-separated skill names, or '*' for all own-posture skills")
    parser.add_argument("--connectors", default="", help="comma-separated connector names, or '*' for all with real wiring")
    parser.add_argument("--agents", default="", help="comma-separated agent names, or '*' for all own-posture agents")
    parser.add_argument("--assistants", default="", help="comma-separated assistant names, or '*' for all own-posture assistants")
    parser.add_argument("--activity", action="append", default=[], metavar="TITLE", help=(
        "install everything a Delivery-pipeline activity uses (matched against factory-data.json's "
        "activities by title, e.g. 'Readiness & simplification analysis'); repeatable to install "
        "several activities at once, and combines with --skills/--connectors if those are given "
        "too. Fails immediately if any activity references a skill or connector this adapter "
        "can't install, rather than partially installing the rest."
    ))
    parser.add_argument("--use-case", action="append", default=[], metavar="USE_CASE_ID",
                         help="install every Assistant/Agent whose use_case_ids includes this stable ID, plus everything they need; repeatable")
    parser.add_argument("--destination", action="append", default=[], metavar="CONNECTOR=NAME",
                         help="override the <destination> credential-file name for one connector; repeatable")
    parser.add_argument("--check", action="store_true", help="report drift against factory-lock.json, write nothing")
    parser.add_argument("--force", action="store_true", help="reinstall even if content hash is unchanged")
    args = parser.parse_args(argv)

    project = common.check_project_path(args.project)

    destinations = {}
    for item in args.destination:
        if "=" not in item:
            common.die(f"--destination must be CONNECTOR=NAME, got '{item}'")
        k, v = item.split("=", 1)
        destinations[k] = v

    skill_names, connector_names, agent_names, assistant_names, activities = common.resolve_selection(
        args.skills, args.connectors, args.agents, args.activity, ADOPT_HINT,
        assistants_csv=args.assistants, use_case_queries=args.use_case,
    )
    for activity in activities:
        print(f"Activity: {activity['title']} ({activity['file']})")

    # Complete-path expansion (EPMCSAPAI-330/AI Artifacts v0.3): whatever was explicitly
    # requested above is just the seed set. Everything each seed's own Dependency graph names
    # (Assistant -> Agent -> Skill -> Tool -> Connector/Artifact/Knowledge Source) is pulled in
    # automatically from here on, so e.g. --assistants alone is enough to install everything it
    # needs -- --skills/--agents/--tools stay useful for testing one component in isolation.
    expanded = common.expand_dependencies(
        skill_names=skill_names, agent_names=agent_names, assistant_names=assistant_names,
        connector_names=connector_names,
    )
    existing, missing = common.split_existing(expanded)
    for kind, names in missing.items():
        if names:
            print(f"Note: {kind} not yet built, skipped (forward-declared): {', '.join(names)}")
    skill_names = existing["skills"]
    agent_names = existing["agents"]
    assistant_names = existing["assistants"]
    connector_names = existing["connectors"]
    graph_tools = existing["tools"]
    graph_artifacts = existing["artifacts"]
    graph_knowledge_sources = existing["knowledge_sources"]

    version = common.factory_version()
    lock = common.load_lock(project)
    drift = []
    skills_root = project / ".claude" / "skills"

    installed_skills = []
    for name in skill_names:
        src_hash = common.hash_tree(common.SKILLS_DIR / name, ignore_suffixes=(".meta.md",))
        prior = lock["skills"].get(name, {})
        unchanged = prior.get("contentHash") == src_hash
        dest = skills_root / name
        dest_matches = dest.exists() and common.hash_tree(dest) == src_hash
        if unchanged and dest_matches and not args.force:
            installed_skills.append(name)
            continue
        if not unchanged:
            reason = "factory source changed"
        elif not dest.exists():
            reason = "not yet installed"
        else:
            reason = "local copy was hand-edited, overwriting with factory source"
        drift.append(f"skill '{name}': {reason}")
        if args.check:
            continue
        common.copy_skill(name, skills_root)
        lock["skills"][name] = {
            "source": f"skills/{name}",
            "contentHash": src_hash,
            "installedTo": f".claude/skills/{name}",
        }
        installed_skills.append(name)

    agents_root = project / ".claude" / "agents"
    installed_agents = []
    for name in agent_names:
        src_hash = common.hash_bytes(common.agent_output_bytes(name))
        prior = lock["agents"].get(name, {})
        unchanged = prior.get("contentHash") == src_hash
        dest = agents_root / f"{name}.md"
        dest_matches = dest.exists() and common.hash_file(dest) == src_hash
        if unchanged and dest_matches and not args.force:
            installed_agents.append(name)
            continue
        if not unchanged:
            reason = "factory source changed"
        elif not dest.exists():
            reason = "not yet installed"
        else:
            reason = "local copy was hand-edited, overwriting with factory source"
        drift.append(f"agent '{name}': {reason}")
        if args.check:
            continue
        common.copy_agent(name, dest)
        lock["agents"][name] = {
            "source": f"agents/{name}",
            "contentHash": src_hash,
            "installedTo": f".claude/agents/{name}.md",
        }
        installed_agents.append(name)

    installed_assistants = []
    for name in assistant_names:
        src_hash = common.hash_bytes(common.assistant_output_bytes(name))
        prior = lock["assistants"].get(name, {})
        unchanged = prior.get("contentHash") == src_hash
        dest = agents_root / f"{name}.md"
        dest_matches = dest.exists() and common.hash_file(dest) == src_hash
        if unchanged and dest_matches and not args.force:
            installed_assistants.append(name)
            continue
        if not unchanged:
            reason = "factory source changed"
        elif not dest.exists():
            reason = "not yet installed"
        else:
            reason = "local copy was hand-edited, overwriting with factory source"
        drift.append(f"assistant '{name}': {reason}")
        if args.check:
            continue
        common.copy_assistant(name, dest)
        lock["assistants"][name] = {
            "source": f"assistants/{name}",
            "contentHash": src_hash,
            "installedTo": f".claude/agents/{name}.md",
        }
        installed_assistants.append(name)

    tools_root = project / "tools"
    installed_tools = []
    for name in graph_tools:
        src_hash = common.hash_tree(common.TOOLS_DIR / name, ignore_suffixes=(".meta.md",))
        prior = lock["tools"].get(name, {})
        unchanged = prior.get("contentHash") == src_hash
        dest = tools_root / name
        dest_matches = dest.exists() and common.hash_tree(dest) == src_hash
        if unchanged and dest_matches and not args.force:
            installed_tools.append(name)
            continue
        if not unchanged:
            reason = "factory source changed"
        elif not dest.exists():
            reason = "not yet installed"
        else:
            reason = "local copy was hand-edited, overwriting with factory source"
        drift.append(f"tool '{name}': {reason}")
        if args.check:
            continue
        common.copy_tool(name, tools_root)
        lock["tools"][name] = {
            "source": f"tools/{name}",
            "contentHash": src_hash,
            "installedTo": f"tools/{name}",
        }
        installed_tools.append(name)

    seeded_knowledge, seeded_artifacts = [], []
    for bucket in common.prose_referenced_knowledge_buckets(skill_names, graph_knowledge_sources):
        dest = project / "knowledge" / bucket
        if args.check:
            if not dest.exists():
                drift.append(f"knowledge '{bucket}': not yet seeded")
            continue
        prior = lock["knowledge"].get(bucket, {})
        copied, content_hash = common.seed_reference_dir(common.KNOWLEDGE_DIR / bucket, dest)
        if copied:
            drift.append(f"knowledge '{bucket}': seeded")
        if "contentHash" not in prior:
            if not copied:
                drift.append(f"knowledge '{bucket}': backfilling lock entry (was already seeded, untracked)")
            lock["knowledge"][bucket] = {
                "source": f"knowledge/{bucket}",
                "seededAt": prior.get("seededAt", common.now_iso()),
                "contentHash": content_hash,
            }
        seeded_knowledge.append(bucket)
    for name in dict.fromkeys(list(common.referenced_names(skill_names, "artifacts")) + graph_artifacts):
        dest = project / "artifacts" / name
        if args.check:
            if not dest.exists():
                drift.append(f"artifact '{name}': not yet seeded")
            continue
        prior = lock["artifacts"].get(name, {})
        copied, content_hash = common.seed_reference_dir(common.ARTIFACTS_DIR / name, dest)
        if copied:
            drift.append(f"artifact '{name}': seeded")
        if "contentHash" not in prior:
            if not copied:
                drift.append(f"artifact '{name}': backfilling lock entry (was already seeded, untracked)")
            lock["artifacts"][name] = {
                "source": f"artifacts/{name}",
                "seededAt": prior.get("seededAt", common.now_iso()),
                "contentHash": content_hash,
            }
        seeded_artifacts.append(name)

    for source_id, src_path in common.knowledge_source_paths(graph_knowledge_sources):
        rel = src_path.relative_to(common.KNOWLEDGE_DIR)
        dest = project / "knowledge" / rel
        if args.check:
            if not dest.exists():
                drift.append(f"knowledge_source '{source_id}': not yet seeded")
            continue
        prior = lock["knowledge"].get(source_id, {})
        copied, content_hash = common.seed_reference_dir(src_path, dest)
        if copied:
            drift.append(f"knowledge_source '{source_id}': seeded")
        if "contentHash" not in prior:
            if not copied:
                drift.append(f"knowledge_source '{source_id}': backfilling lock entry (was already seeded, untracked)")
            # Normalized to always carry the "knowledge/" prefix -- bucket entries above already
            # did; knowledge_source entries previously didn't, an inconsistency that made the two
            # halves of this same map not directly comparable.
            lock["knowledge"][source_id] = {
                "source": f"knowledge/{rel.as_posix()}",
                "seededAt": prior.get("seededAt", common.now_iso()),
                "contentHash": content_hash,
            }
        if str(rel) not in seeded_knowledge:
            seeded_knowledge.append(str(rel))

    installed_connectors = []
    mcp_entries = {}
    for name in connector_names:
        entries, src_hash, dest_name = common.normalize_connector(name, destinations, tool=TOOL)
        mcp_entries.update(entries)
        prior = lock["connectors"].get(name, {})
        unchanged = prior.get("contentHash") == src_hash and prior.get("destination") == dest_name
        if not unchanged or args.force:
            drift.append(f"connector '{name}' wiring changed")
        if not args.check:
            common.copy_connector(name, project)
            lock["connectors"][name] = {
                "source": f"connectors/{name}/server.json",
                "contentHash": src_hash,
                "destination": dest_name,
                "installedTo": f"connectors/{name}",
            }
        installed_connectors.append(name)

    if args.check:
        if drift:
            print("Drift found:")
            for d in drift:
                print(f"  - {d}")
            sys.exit(1)
        print("Up to date.")
        return

    if mcp_entries:
        write_mcp_json(project, mcp_entries)
    write_claude_md(project, installed_skills, installed_agents, installed_assistants, installed_connectors, seeded_knowledge, seeded_artifacts, version)
    pruned = prune_orphaned_lock_entries(lock)
    common.write_lock(project, lock, version, TOOL)
    if pruned:
        for section, names in pruned.items():
            print(f"Pruned orphaned lock entries ({section}, factory source gone): {', '.join(names)}")

    if drift:
        print(f"Installed/updated: {', '.join(drift)}")
    else:
        print("Up to date -- nothing to reinstall (use --force to override).")
    print(f"Skills: {', '.join(installed_skills) or '(none)'}")
    if installed_assistants:
        print(f"Assistants: {', '.join(installed_assistants)}")
    if installed_agents:
        print(f"Agents: {', '.join(installed_agents)}")
    if installed_tools:
        print(f"Tools: {', '.join(installed_tools)}")
    print(f"Connectors: {', '.join(installed_connectors) or '(none)'}")
    if seeded_knowledge:
        print(f"Knowledge (seeded once, yours to edit): {', '.join(seeded_knowledge)}")
    if seeded_artifacts:
        print(f"Artifacts (seeded once, yours to edit): {', '.join(seeded_artifacts)}")


if __name__ == "__main__":
    main()
