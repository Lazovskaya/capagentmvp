#!/usr/bin/env python3
"""Convert SAP Activate roadmap XML to markdown knowledge files.

Supports two XML formats:
  - MSPDI  (namespace http://schemas.microsoft.com/project) — MS Project export
  - cProjects (namespace urn:cProjects) — SAP Solution Manager export
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

# ---------------------------------------------------------------------------
# MSPDI (MS Project XML)
# ---------------------------------------------------------------------------
MSPDI_NS = "http://schemas.microsoft.com/project"
MP = lambda name: f"{{{MSPDI_NS}}}{name}"


def _mspdi_duration_days(pt: str) -> float | None:
    """Convert PT8H0M0S → float days (8 h = 1 day)."""
    if not pt:
        return None
    m = re.match(r"PT(\d+(?:\.\d+)?)H", pt)
    if not m:
        return None
    hours = float(m.group(1))
    return round(hours / 8, 2) if hours else None


def _mspdi_fieldid_map(root: ET.Element) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for ea in root.findall(f"{MP('ExtendedAttributes')}/{MP('ExtendedAttribute')}"):
        fid = ea.findtext(MP("FieldID"), "")
        alias = ea.findtext(MP("Alias"), "")
        if fid and alias:
            mapping[fid] = alias
    return mapping


def _mspdi_ext_attrs(task: ET.Element, fieldmap: dict[str, str]) -> dict[str, str]:
    result: dict[str, str] = {}
    for ea in task.findall(MP("ExtendedAttribute")):
        fid = ea.findtext(MP("FieldID"), "")
        val = (ea.findtext(MP("Value"), "") or "").strip()
        if fid in fieldmap and val:
            result[fieldmap[fid]] = val
    return result


def _render_tags(attrs: dict[str, str]) -> str:
    parts = []
    for key in ("Workstream", "Assembly Category", "SIG", "Tags"):
        if key in attrs:
            parts.append(f"**{key}:** {attrs[key]}")
    return "  \n".join(parts)


def parse_mspdi(xml_path: Path, label: str) -> str:
    tree = ET.parse(xml_path)
    root = tree.getroot()
    fieldmap = _mspdi_fieldid_map(root)
    tasks = root.findall(f"{MP('Tasks')}/{MP('Task')}")

    lines = [
        f"# {label}\n",
        "<!-- Generated by tools/generate_activate_roadmap_markdown.py — do not edit manually -->\n",
    ]

    for task in tasks:
        level = int(task.findtext(MP("OutlineLevel"), "0"))
        if level < 2:
            continue

        name = (task.findtext(MP("Name"), "") or "").strip()
        wbs = (task.findtext(MP("OutlineNumber"), task.findtext(MP("WBS"), "")) or "").strip()
        is_milestone = task.findtext(MP("Milestone"), "0") == "1"
        days = _mspdi_duration_days(task.findtext(MP("Duration"), "") or "")
        attrs = _mspdi_ext_attrs(task, fieldmap)
        tag_block = _render_tags(attrs)
        dur = f" _{days}d_" if days else ""

        if level == 2:
            lines.append(f"\n## {wbs}. {name}\n")
        elif level == 3:
            lines.append(f"\n### {wbs} {name}\n")
            if tag_block:
                lines.append(tag_block + "\n")
        elif level == 4:
            marker = "🏁 " if is_milestone else ""
            lines.append(f"\n#### {marker}{wbs} {name}{dur}\n")
            if tag_block:
                lines.append(tag_block + "\n")
        elif level == 5:
            lines.append(f"\n##### {wbs} {name}{dur}\n")
            if tag_block:
                lines.append(tag_block + "\n")
        elif level == 6:
            lines.append(f"\n###### {wbs} {name}{dur}\n")
            if tag_block:
                lines.append(tag_block + "\n")
        elif level >= 7:
            indent = "  " * (level - 6)
            lines.append(f"{indent}- **{name}**\n")

    return "".join(lines)


# ---------------------------------------------------------------------------
# cProjects (SAP Solution Manager XML)
# ---------------------------------------------------------------------------

def _cpr_full_name(td: ET.Element) -> str:
    """Extract full task name: LONGTEXT 'Title:X-' prefix takes priority over truncated DESCRIPTION."""
    lt = (td.findtext("LONGTEXT", "") or "").strip()
    if lt.startswith("Title:"):
        # Format: "Title:Full Name-\xa0Description:..."
        body = lt[len("Title:"):]
        # split on "-\xa0" or "- Description:" or just "-" before "Description:"
        for sep in ("-\xa0", "-\u00a0", "- "):
            idx = body.find(sep)
            if idx > 0:
                return body[:idx].strip()
        # fallback: take up to first dash if reasonable
        idx = body.find("-")
        if 0 < idx < 120:
            return body[:idx].strip()
    return (td.findtext("DESCRIPTION", "") or "").strip()


def _cpr_roles_map(root: ET.Element) -> dict[str, str]:
    """Return {NUMBER: DESCRIPTION} for all ProjectRoles."""
    roles: dict[str, str] = {}
    for pr in root.findall(".//ProjectRoleData"):
        num = pr.findtext("NUMBER", "")
        desc = pr.findtext("DESCRIPTION", "")
        if num and desc:
            roles[num] = desc
    return roles


def _cpr_task_roles(task_el: ET.Element, roles: dict[str, str]) -> list[str]:
    return [
        roles.get(a.findtext("NUMBER", ""), "")
        for a in task_el.findall(".//ProjectRoleAssignment")
        if roles.get(a.findtext("NUMBER", ""), "")
    ]


def _cpr_render_roles(role_names: list[str]) -> str:
    unique = list(dict.fromkeys(role_names))  # deduplicate, preserve order
    if not unique:
        return ""
    return f"**Roles:** {', '.join(unique)}"


def _cpr_tasks_to_lines(tasks_el: ET.Element, roles: dict[str, str], lines: list[str]) -> None:
    """Recursively render Task elements from a <Tasks> container."""
    for task in tasks_el.findall("Task"):
        td = task.find("TaskData")
        if td is None:
            continue

        num = (td.findtext("NUMBER", "") or "").strip()
        name = _cpr_full_name(td)
        milestone = (td.findtext("MILESTONE", "FALSE") or "FALSE").upper() == "TRUE"
        role_names = _cpr_task_roles(task, roles)
        role_line = _cpr_render_roles(role_names)

        depth = num.count(".")  # 0 = x, 1 = x.y, 2 = x.y.z …

        if depth == 1:
            lines.append(f"\n### {num} {name}\n")
            if role_line:
                lines.append(role_line + "\n")
        elif depth == 2:
            marker = "🏁 " if milestone else ""
            lines.append(f"\n#### {marker}{num} {name}\n")
            if role_line:
                lines.append(role_line + "\n")
        elif depth == 3:
            lines.append(f"\n##### {num} {name}\n")
            if role_line:
                lines.append(role_line + "\n")
        elif depth >= 4:
            indent = "  " * (depth - 3)
            lines.append(f"{indent}- **{name}**\n")

        sub = task.find("Tasks")
        if sub is not None:
            _cpr_tasks_to_lines(sub, roles, lines)


def parse_cprojects(xml_path: Path, label: str) -> str:
    tree = ET.parse(xml_path)
    root = tree.getroot()
    roles = _cpr_roles_map(root)

    lines = [
        f"# {label}\n",
        "<!-- Generated by tools/generate_activate_roadmap_markdown.py — do not edit manually -->\n",
    ]

    for phase in root.findall(".//Phase"):
        pd = phase.find("PhaseData")
        if pd is None:
            continue
        p_num = (pd.findtext("NUMBER", "") or "").strip()
        p_name = (pd.findtext("DESCRIPTION", "") or "").strip()
        lines.append(f"\n## {p_num}. {p_name}\n")

        tasks_el = phase.find("Tasks")
        if tasks_el is not None:
            _cpr_tasks_to_lines(tasks_el, roles, lines)

    return "".join(lines)


# ---------------------------------------------------------------------------
# Format detection
# ---------------------------------------------------------------------------

def detect_format(xml_path: Path) -> str:
    """Return 'mspdi' or 'cprojects' based on root element namespace."""
    for _, elem in ET.iterparse(xml_path, events=("start",)):
        ns = elem.tag.split("}")[0].lstrip("{") if "}" in elem.tag else ""
        if "microsoft.com/project" in ns:
            return "mspdi"
        return "cprojects"
    return "mspdi"


