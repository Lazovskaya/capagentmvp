#!/usr/bin/env python3
"""Generate curated-markdown layer for the sap-best-practices domain pack.

Reads the regenerable scope-item JSON cache and produces three kinds of
committed markdown:

  knowledge/domain-packs/sap-best-practices/
    taxonomy-overview.md          — L1/L2/L3 hierarchy table + full index
    dependency-map.md             — cross-scope-item dependency graph
    value-streams/
      <slug>.md                   — one file per L1 value stream

All output files are auto-generated; re-run this script after any
scope-item cache regeneration (ingest → enrich → bpmn → populate_l1).
Files that already exist are overwritten in full — do not hand-edit them.
Consultant notes belong in separate, un-generated files (e.g. a
troubleshooting/ folder) that this script never touches.

Usage:
    python3 tools/generate_sap_bp_markdown.py
    python3 tools/generate_sap_bp_markdown.py --dry-run   # print stats, no write
"""

import argparse
import json
import re
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCOPE_ITEMS_DIR = REPO_ROOT / "knowledge/domain-packs/sap-best-practices/scope-items"
OUT_DIR = REPO_ROOT / "knowledge/domain-packs/sap-best-practices"
VALUE_STREAMS_DIR = OUT_DIR / "value-streams"

GENERATED_BANNER = (
    "<!-- AUTO-GENERATED by tools/generate_sap_bp_markdown.py — do not edit by hand.\n"
    "     Re-run after scope-item cache regeneration (ingest → enrich → bpmn → populate_l1). -->\n"
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def load_scope_items(directory: Path) -> list[dict]:
    items = []
    for path in sorted(directory.glob("*.json")):
        with path.open() as f:
            items.append(json.load(f))
    return items


def normalise_l2(raw) -> list[str]:
    """Return a clean list of L2 values regardless of whether raw is str/list/None."""
    if raw is None:
        return []
    if isinstance(raw, str):
        return [raw] if raw.strip() else []
    return [v for v in raw if isinstance(v, str) and v.strip()]


def key_roles(item: dict, max_roles: int = 4) -> list[str]:
    """Extract unique human-readable roles from L4_steps, deduplicated."""
    seen = []
    for step in item["hierarchy"].get("L4_steps") or []:
        for part in (step.get("role") or "").split("|"):
            role = part.strip()
            if role and role not in seen:
                seen.append(role)
    return seen[:max_roles]


def bpmn_step_count(item: dict) -> int:
    return len((item.get("bpmn_flow") or {}).get("steps") or [])


def mandatory_deps(item: dict) -> list[str]:
    return [
        d["scope_item_id"]
        for d in (item.get("bpmn_flow") or {}).get("dependencies") or []
        if not d.get("optional")
    ]


def optional_deps(item: dict) -> list[str]:
    return [
        d["scope_item_id"]
        for d in (item.get("bpmn_flow") or {}).get("dependencies") or []
        if d.get("optional")
    ]


# ---------------------------------------------------------------------------
# Build index structures
# ---------------------------------------------------------------------------

def build_index(items: list[dict]):
    """Return nested dicts: l1_map[l1][l2] = [item, ...] plus lookup by id."""
    l1_map: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    by_id: dict[str, dict] = {}

    for item in items:
        h = item["hierarchy"]
        l1_values = h.get("L1_value_stream") or ["(Unclassified)"]
        l2_values = normalise_l2(h.get("L2_core_process")) or ["(Unknown)"]
        by_id[item["scope_item_id"]] = item
        for l1 in l1_values:
            for l2 in l2_values:
                l1_map[l1][l2].append(item)

    return l1_map, by_id


# ---------------------------------------------------------------------------
# taxonomy-overview.md
# ---------------------------------------------------------------------------

def generate_taxonomy_overview(l1_map: dict, items: list[dict]) -> str:
    today = date.today().isoformat()
    lines = [
        GENERATED_BANNER,
        "# SAP Best Practices — taxonomy overview\n",
        f"Generated {today} from {len(items)} scope items.\n",
        "## L1 value streams\n",
        "| L1 value stream | Scope items | L2 process groups |",
        "|---|---|---|",
    ]
    for l1, l2_map in sorted(l1_map.items()):
        total = sum(len(v) for v in l2_map.values())
        slug = slugify(l1)
        lines.append(
            f"| [{l1}](value-streams/{slug}.md) | {total} | {len(l2_map)} |"
        )
    lines += [
        "",
        "## L1 → L2 → scope items\n",
    ]
    for l1, l2_map in sorted(l1_map.items()):
        slug = slugify(l1)
        total = sum(len(v) for v in l2_map.values())
        lines.append(f"### {l1} ({total} scope items)\n")
        for l2, scope_items in sorted(l2_map.items()):
            codes = ", ".join(
                f"`{s['scope_item_id']}`" for s in sorted(scope_items, key=lambda x: x["scope_item_id"])
            )
            lines.append(f"**{l2}** ({len(scope_items)}): {codes}\n")
        lines.append("")

    lines += [
        "## Full alphabetical index\n",
        "| Code | Title | L1 | L2 | Steps | Deps |",
        "|---|---|---|---|---|---|",
    ]
    for item in sorted(items, key=lambda x: x["scope_item_id"]):
        h = item["hierarchy"]
        l1 = ", ".join(h.get("L1_value_stream") or ["—"])
        l2 = ", ".join(normalise_l2(h.get("L2_core_process")) or ["—"])
        steps = bpmn_step_count(item)
        deps = len(mandatory_deps(item)) + len(optional_deps(item))
        lines.append(
            f"| `{item['scope_item_id']}` | {item['title']} | {l1} | {l2} | {steps} | {deps} |"
        )

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# value-streams/<slug>.md
# ---------------------------------------------------------------------------

def generate_value_stream(l1: str, l2_map: dict, by_id: dict) -> str:
    today = date.today().isoformat()
    total = sum(len(v) for v in l2_map.values())
    lines = [
        GENERATED_BANNER,
        f"# {l1}\n",
        f"Generated {today}. {total} scope items across {len(l2_map)} process groups.\n",
    ]

    for l2, scope_items in sorted(l2_map.items()):
        lines += [
            f"## {l2}\n",
            f"{len(scope_items)} scope items.\n",
            "| Code | Title | Steps | Mandatory deps | Optional deps | Key roles |",
            "|---|---|---|---|---|---|",
        ]
        for item in sorted(scope_items, key=lambda x: x["scope_item_id"]):
            steps = bpmn_step_count(item)
            m_deps = mandatory_deps(item)
            o_deps = optional_deps(item)
            roles = key_roles(item)
            m_str = " ".join(f"`{d}`" for d in m_deps) if m_deps else "—"
            o_str = " ".join(f"`{d}`" for d in o_deps) if o_deps else "—"
            roles_str = ", ".join(roles) if roles else "—"
            lines.append(
                f"| `{item['scope_item_id']}` | {item['title']} | {steps} | {m_str} | {o_str} | {roles_str} |"
            )
        lines.append("")

        # BPMN step detail for items that have steps
        for item in sorted(scope_items, key=lambda x: x["scope_item_id"]):
            bf = item.get("bpmn_flow") or {}
            steps = bf.get("steps") or []
            if not steps:
                continue
            lines += [
                f"### {item['scope_item_id']} — {item['title']}\n",
                "**Process steps** (BPMN execution order):\n",
            ]
            for s in steps:
                opt_marker = " *(optional)*" if s.get("optional") else ""
                role = s.get("role") or "—"
                name = s["name"]
                dep_ref = ""
                if s.get("calls_scope_item"):
                    dep_ref = f" → calls `{s['calls_scope_item']}`"
                lines.append(f"{s['seq']}. **{name}**{opt_marker} — *{role}*{dep_ref}")
            lines.append("")

            # Key Fiori apps from L4
            fiori = [
                s for s in (item["hierarchy"].get("L4_steps") or [])
                if s.get("fiori_app_id")
            ]
            if fiori:
                lines += ["**Key Fiori apps / TCodes:**\n"]
                for s in fiori[:8]:
                    tcode = f" / `{s['technical_transaction']}`" if s.get("technical_transaction") else ""
                    lines.append(f"- `{s['fiori_app_id']}`{tcode} — {s['name']}")
                if len(fiori) > 8:
                    lines.append(f"- *…and {len(fiori) - 8} more (see scope-items/{item['scope_item_id']}.json)*")
                lines.append("")

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# dependency-map.md
# ---------------------------------------------------------------------------

def generate_dependency_map(items: list[dict], by_id: dict) -> str:
    today = date.today().isoformat()
    lines = [
        GENERATED_BANNER,
        "# SAP Best Practices — cross-scope-item dependency map\n",
        f"Generated {today}. Shows subprocess dependencies extracted from BPMN models.\n",
        "A dependency means the scope item's BPMN diagram calls the other as a subprocess.\n",
        "## Items with mandatory dependencies\n",
        "| Scope item | Title | Calls (mandatory) | Calls (optional) |",
        "|---|---|---|---|",
    ]

    # Items that CALL others
    callers = [i for i in items if mandatory_deps(i) or optional_deps(i)]
    for item in sorted(callers, key=lambda x: x["scope_item_id"]):
        m = " ".join(f"`{d}`" for d in mandatory_deps(item)) or "—"
        o = " ".join(f"`{d}`" for d in optional_deps(item)) or "—"
        lines.append(f"| `{item['scope_item_id']}` | {item['title']} | {m} | {o} |")

    lines += [
        "",
        "## Items called by others (reverse index)\n",
        "| Scope item | Title | Called by |",
        "|---|---|---|",
    ]

    # Reverse index: who calls whom
    called_by: dict[str, list[str]] = defaultdict(list)
    for item in items:
        for dep_id in mandatory_deps(item) + optional_deps(item):
            called_by[dep_id].append(item["scope_item_id"])

    for dep_id, callers_list in sorted(called_by.items()):
        title = by_id.get(dep_id, {}).get("title", "—")
        callers_str = " ".join(f"`{c}`" for c in sorted(callers_list))
        lines.append(f"| `{dep_id}` | {title} | {callers_str} |")

    lines += [
        "",
        "## Dependency clusters\n",
        "Scope items with 3+ callers (most reused subprocesses):\n",
        "| Scope item | Title | Caller count | Callers |",
        "|---|---|---|---|",
    ]
    for dep_id, callers_list in sorted(called_by.items(), key=lambda x: -len(x[1])):
        if len(callers_list) < 3:
            break
        title = by_id.get(dep_id, {}).get("title", "—")
        callers_str = " ".join(f"`{c}`" for c in sorted(callers_list))
        lines.append(f"| `{dep_id}` | {title} | {len(callers_list)} | {callers_str} |")

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="Print stats only, do not write files")
    parser.add_argument(
        "--scope-items-dir",
        type=Path,
        default=SCOPE_ITEMS_DIR,
        help="Path to scope-items/ directory (default: %(default)s)",
    )
    args = parser.parse_args()

    scope_items_dir: Path = args.scope_items_dir
    if not scope_items_dir.exists():
        print(f"ERROR: scope-items dir not found: {scope_items_dir}", file=sys.stderr)
        sys.exit(1)

    print(f"Loading scope items from {scope_items_dir} …")
    items = load_scope_items(scope_items_dir)
    print(f"Loaded {len(items)} scope items.")

    l1_map, by_id = build_index(items)

    steps_count = sum(1 for i in items if bpmn_step_count(i) > 0)
    deps_count = sum(1 for i in items if mandatory_deps(i) or optional_deps(i))
    print(f"  L1 value streams: {len(l1_map)}")
    print(f"  Scope items with BPMN steps: {steps_count}")
    print(f"  Scope items with dependencies: {deps_count}")

    if args.dry_run:
        print("Dry run — no files written.")
        return

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    VALUE_STREAMS_DIR.mkdir(parents=True, exist_ok=True)

    # taxonomy-overview.md
    taxonomy_path = OUT_DIR / "taxonomy-overview.md"
    taxonomy_path.write_text(generate_taxonomy_overview(l1_map, items), encoding="utf-8")
    print(f"  wrote {taxonomy_path.relative_to(REPO_ROOT)}")

    # dependency-map.md
    dep_path = OUT_DIR / "dependency-map.md"
    dep_path.write_text(generate_dependency_map(items, by_id), encoding="utf-8")
    print(f"  wrote {dep_path.relative_to(REPO_ROOT)}")

    # value-streams/<slug>.md
    written = 0
    for l1, l2_map in sorted(l1_map.items()):
        slug = slugify(l1)
        vs_path = VALUE_STREAMS_DIR / f"{slug}.md"
        vs_path.write_text(generate_value_stream(l1, l2_map, by_id), encoding="utf-8")
        written += 1
    print(f"  wrote {written} value-stream files → {VALUE_STREAMS_DIR.relative_to(REPO_ROOT)}/")

    print("Done.")


if __name__ == "__main__":
    main()
