def main() -> None:
    repo_root = Path(__file__).parent.parent
    out_dir = repo_root / "knowledge" / "methodology" / "activate-s4hc-pe"
    out_dir.mkdir(parents=True, exist_ok=True)

    parsers = {"mspdi": parse_mspdi, "cprojects": parse_cprojects}

    for spec in ROADMAPS:
        xml_path = repo_root / spec["xml"]
        if not xml_path.exists():
            print(f"SKIP (not found): {xml_path.name}", file=sys.stderr)
            continue

        fmt = detect_format(xml_path)
        out_path = out_dir / spec["out"]
        print(f"Parsing [{fmt}] {xml_path.name} …")
        md = parsers[fmt](xml_path, spec["label"])
        out_path.write_text(md, encoding="utf-8")
        print(f"  → {out_path.relative_to(repo_root)}")

    print("Done.")


if __name__ == "__main__":
    main()
