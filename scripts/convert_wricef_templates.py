#!/usr/bin/env python3
"""Convert WRICEF FS Word templates (.docm/.docx) to markdown artifacts.

For each spec file in workspace/specs/ produces:
  artifacts/wricef-<type>/template.md
  artifacts/wricef-<type>/schema.json
  artifacts/wricef-<type>/artifact.meta.md  (empty, consistent with factory pattern)
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

from docx import Document  # pip install python-docx
from docx.oxml.ns import qn

# ---------------------------------------------------------------------------
# Word file helpers
# ---------------------------------------------------------------------------

def _open_word(src: Path) -> Document:
    """Open .docx or .docm (patches content-type for macro-enabled files)."""
    if src.suffix.lower() == ".docx":
        return Document(str(src))
    tmp = tempfile.NamedTemporaryFile(suffix=".docx", delete=False)
    tmp.close()
    shutil.copy2(src, tmp.name)
    with zipfile.ZipFile(tmp.name, "r") as zin:
        contents = {n: zin.read(n) for n in zin.namelist()}
    ct = contents["[Content_Types].xml"].decode()
    ct = ct.replace(
        "application/vnd.ms-word.document.macroEnabled.main+xml",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml",
    )
    contents["[Content_Types].xml"] = ct.encode()
    with zipfile.ZipFile(tmp.name, "w", zipfile.ZIP_DEFLATED) as zout:
        for n, data in contents.items():
            zout.writestr(n, data)
    return Document(tmp.name)


def _para_text(para) -> str:
    return para.text.strip()


def _table_to_md(table) -> str:
    rows = []
    for i, row in enumerate(table.rows):
        cells = [c.text.strip().replace("\n", " ") for c in row.cells]
        rows.append("| " + " | ".join(cells) + " |")
        if i == 0:
            rows.append("| " + " | ".join(["---"] * len(cells)) + " |")
    return "\n".join(rows)


# ---------------------------------------------------------------------------
# Document → markdown
# ---------------------------------------------------------------------------

STYLE_LEVEL = {
    "Heading 1": 1, "Heading 2": 2, "Heading 3": 3,
    "Appendix": 2, "Appendix Heading": 2,
    "Title": 0,
}

SKIP_TEXTS = {
    "Note. Master copy of this document, with signatories, is held on Solution Manager",
    "Role and Reason for Approval",
    "Table of ContentS",
}

# Skip cover/boilerplate table styles
SKIP_TABLE_STYLES = {"_Cover_Title", "ConfidentialStatus"}

# Red/guidance text markers — strip these lines as they're Word-only instructions
GUIDANCE_RE = re.compile(r"^\{.+\}$|^<.+>$")

# TOC styles — skip
TOC_STYLES = {"TOC", "toc 1", "toc 2", "toc 3", "toc 4"}

# Boilerplate body text in FS templates (approval block content)
BOILERPLATE_RE = re.compile(
    r"^(The author is signing|The SAP Solution Lead|The SAP Development Lead|FUNCTIONAL SPECIFICATION|ABAP custom|14/06/2017|Roger Sainsbury|Initial draft|Version\s+Date\s+Name|DATE:)",
    re.IGNORECASE,
)

# Cover/approval/version tables to skip in FS templates
def _is_cover_table(table) -> bool:
    """Skip FS cover/approval/version-history tables."""
    try:
        all_text = " ".join(c.text for row in table.rows for c in row.cells).upper()
        return any(kw in all_text for kw in (
            "FUNCTIONAL SPECIFICATION", "REASON FOR APPROVAL",
            "ALTERATION REASON", "ROGER SAINSBURY", "14/06/2017",
        ))
    except Exception:
        return False


# Every WRICEF-family artifact's schema.json requires wricef_id, decision_log_row_id and
# status regardless of what a given source Word template's own sections cover -- these are
# this factory's own traceability fields (WRICEF ID, the FTS decision-log row that produced
# the delta, lifecycle status), not something the client's FS template was ever going to
# carry. Emit them explicitly rather than relying on the source doc to happen to have them.
HEADER_BLOCK = [
    "**WRICEF ID:**",
    "",
    "**Decision log row ID:**",
    "",
    "**Status:** Draft / In Review / Approved / Superseded",
    "",
]


def doc_to_markdown(doc: Document, label: str) -> str:
    lines: list[str] = [
        f"# {label}",
        "",
        "<!-- Generated by tools/convert_wricef_templates.py — do not edit manually -->",
        "",
        *HEADER_BLOCK,
    ]

    body = doc.element.body
    for child in body:
        tag = child.tag.split("}")[-1] if "}" in child.tag else child.tag

        if tag == "p":
            # paragraph
            from docx.text.paragraph import Paragraph
            para = Paragraph(child, doc)
            text = _para_text(para)
            style = para.style.name if para.style else "Normal"

            if not text or text in SKIP_TEXTS or GUIDANCE_RE.match(text):
                continue
            if style in TOC_STYLES:
                continue
            if BOILERPLATE_RE.match(text):
                continue

            level = STYLE_LEVEL.get(style)
            if level is not None:
                if level == 0:
                    continue  # Title already in h1
                prefix = "#" * (level + 1)
                lines.append(f"{prefix} {text}")
            else:
                # Skip guidance prose (BodyCopy) in scenario doc — keep for FS templates
                lines.append(text)
            lines.append("")

        elif tag == "tbl":
            from docx.table import Table
            table = Table(child, doc)
            if _is_cover_table(table):
                continue
            lines.append(_table_to_md(table))
            lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Schema generator — derive from section headings
# ---------------------------------------------------------------------------

def make_schema(label: str, sections: list[str]) -> dict:
    props = {}
    for s in sections:
        key = re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")
        props[key] = {"type": "string", "description": s}
    return {
        "type": "object",
        "description": f"Functional Specification — {label}. Produced by solution-design for a confirmed WRICEF delta.",
        "required": ["wricef_id", "decision_log_row_id", "status"],
        "properties": {
            "wricef_id": {"type": "string", "description": "Unique WRICEF ID (e.g. RPT-001, WF-003)"},
            "decision_log_row_id": {"type": "string", "description": "FTS Row ID that produced this delta"},
            "status": {
                "type": "string",
                "enum": ["Draft", "In Review", "Approved", "Superseded"],
                "description": "Document lifecycle status",
            },
            **props,
        },
    }


# ---------------------------------------------------------------------------
# File registry
# ---------------------------------------------------------------------------

STYLE_LEVEL_SCENARIO = {
    "Heading 1": 1, "Heading 2": 2, "Heading 3": 3,
}

SKIP_STYLE_SCENARIO = {"_Cover_Title", "ConfidentialStatus", "TOC", "toc 1", "toc 2", "toc 3", "BodyCopy"}


def doc_to_markdown_scenario(doc: Document, label: str) -> str:
    """Convert a Business Scenario Design .docx (skip guidance prose, keep structure + tables)."""
    lines: list[str] = [
        f"# {label}",
        "",
        "<!-- Generated by tools/convert_wricef_templates.py — do not edit manually -->",
        "",
        *HEADER_BLOCK,
    ]
    from docx.text.paragraph import Paragraph
    from docx.table import Table

    body = doc.element.body
    for child in body:
        tag = child.tag.split("}")[-1] if "}" in child.tag else child.tag

        if tag == "p":
            para = Paragraph(child, doc)
            text = _para_text(para)
            style = para.style.name if para.style else "Normal"
            if not text or text in SKIP_TEXTS or style in SKIP_STYLE_SCENARIO:
                continue
            level = STYLE_LEVEL_SCENARIO.get(style)
            if level is not None:
                lines.append(f"{'#' * (level + 1)} {text}")
                lines.append("")
        elif tag == "tbl":
            table = Table(child, doc)
            if _is_cover_table(table):
                continue
            lines.append(_table_to_md(table))
            lines.append("")

    return "\n".join(lines)


